/**
 * Writes the two committed string modules the shim serves beside MapLibre:
 *
 *   - `src/maplibre-css.generated.ts`: MapLibre's own stylesheet, injected
 *     into the document on first map (no CDN `<link>`).
 *   - `src/licenses.generated.ts`: MapLibre's full LICENSE.txt (BSD-3-Clause
 *     plus the notices of the code it contains), exported so the notice travels
 *     in the served bytes even after minification.
 *
 * Same shape as pouf's `css/*.generated.ts`: a string module the bundle
 * imports by name, so there is no `?inline` default import in shipped code.
 *
 * Regenerate after a maplibre-gl version change: pnpm --dir vibes.diy/google-maps-shim gen
 * Drift guard: test/vendor-generated.test.ts (byte-equal to a fresh run).
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, "..");

export interface VendorSources {
  readonly version: string;
  readonly css: string;
  readonly license: string;
}

export async function readVendorSources(): Promise<VendorSources> {
  const require = createRequire(join(pkgRoot, "package.json"));
  const pkgJsonPath = require.resolve("maplibre-gl/package.json");
  const maplibreRoot = dirname(pkgJsonPath);
  const pkgJson = JSON.parse(await readFile(pkgJsonPath, "utf-8")) as { version: string };
  return {
    version: pkgJson.version,
    css: await readFile(join(maplibreRoot, "dist", "maplibre-gl.css"), "utf-8"),
    license: await readFile(join(maplibreRoot, "LICENSE.txt"), "utf-8"),
  };
}

export function renderCssModule(src: VendorSources): string {
  return [
    `// GENERATED by scripts/gen-vendor.ts from maplibre-gl@${src.version}/dist/maplibre-gl.css. Do not edit.`,
    `export const MAPLIBRE_VERSION = ${JSON.stringify(src.version)};`,
    `export const MAPLIBRE_CSS = ${JSON.stringify(src.css)};`,
    "",
  ].join("\n");
}

export function renderLicenseModule(src: VendorSources): string {
  return [
    `// GENERATED by scripts/gen-vendor.ts from maplibre-gl@${src.version}/LICENSE.txt. Do not edit.`,
    "// Exported data keeps the full redistribution notices in the served bytes.",
    `export const licenses = ${JSON.stringify(`maplibre-gl ${src.version}\n${src.license}`)};`,
    "",
  ].join("\n");
}

export const CSS_MODULE_PATH = join(pkgRoot, "src", "maplibre-css.generated.ts");
export const LICENSE_MODULE_PATH = join(pkgRoot, "src", "licenses.generated.ts");

async function main(): Promise<void> {
  const src = await readVendorSources();
  await writeFile(CSS_MODULE_PATH, renderCssModule(src));
  await writeFile(LICENSE_MODULE_PATH, renderLicenseModule(src));
  console.log(`wrote maplibre-gl@${src.version} css + licenses`);
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  void main();
}
